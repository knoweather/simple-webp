// compareNRGBA compares a decoded image against a raw RGBA reference.
func compareNRGBA(t *testing.T, name string, got image.Image, want []byte) {
	t.Helper()
	nrgba, ok := got.(*image.NRGBA)
	if !ok {
		t.Fatalf("%s: decoded type %T, want *image.NRGBA", name, got)
	}
	if !bytes.Equal(nrgba.Pix, want) {
		w, h := nrgba.Bounds().Dx(), nrgba.Bounds().Dy()
		if len(want) != w*h*4 {
			t.Fatalf("%s: reference is %d bytes, image is %dx%d", name, len(want), w, h)
		}
		diff := 0
		first := -1
		for i := 0; i < len(want); i += 4 {
			if !bytes.Equal(nrgba.Pix[i:i+4], want[i:i+4]) {
				diff++
				if first < 0 {
					first = i / 4
				}
			}
		}
		t.Fatalf("%s: %d of %d pixels differ, first at (%d,%d) got %x want %x",
			name, diff, w*h, first%w, first/w, nrgba.Pix[first*4:first*4+4], want[first*4:first*4+4])
	}
}

// TestDecodeFixtures decodes every testdata/*.webp and compares it with the
// raw RGBA reference generated by libwebp through Pillow.
func TestDecodeFixtures(t *testing.T) {
	entries, err := os.ReadDir("testdata")
	if err != nil {
		t.Skipf("no testdata: %v", err)
	}
	for _, entry := range entries {
		name := entry.Name()
		if !strings.HasSuffix(name, ".webp") {
			continue
		}
		t.Run(strings.TrimSuffix(name, ".webp"), func(t *testing.T) {
			stream, err := os.ReadFile(filepath.Join("testdata", name))
			if err != nil {
				t.Fatal(err)
			}
			golden, err := os.ReadFile(filepath.Join("testdata", strings.TrimSuffix(name, ".webp")+".rgba"))
			if err != nil {
				t.Skipf("no reference pixels: %v", err)
			}
			w, err := ParseWebpBytes(stream)
			if err != nil {
				t.Fatal(err)
			}
			img, err := w.ToImage()
			if err != nil {
				t.Fatal(err)
			}
			if img.Bounds().Dx()*img.Bounds().Dy()*4 != len(golden) {
				t.Fatalf("reference size %d does not match %v", len(golden), img.Bounds())
			}
			if out := os.Getenv("WEBP_DUMP_DIR"); out != "" {
				if nrgba, ok := img.(*image.NRGBA); ok {
					_ = os.WriteFile(filepath.Join(out, strings.TrimSuffix(name, ".webp")+".ours"), nrgba.Pix, 0o644)
				}
			}
			compareNRGBA(t, name, img, golden)
		})
	}
}

// TestImageDecode checks the standard library registration.
func TestImageDecode(t *testing.T) {
	stream, err := os.ReadFile("testdata/gradient.webp")
	if err != nil {
		t.Skip("no fixture")
	}
	img, format, err := image.Decode(bytes.NewReader(stream))
	if err != nil {
		t.Fatal(err)
	}
	if format != "webp" {
		t.Fatalf("format: %q", format)
	}
	cfg, err := DecodeConfig(bytes.NewReader(stream))
	if err != nil {
		t.Fatal(err)
	}
	if cfg.Width != img.Bounds().Dx() || cfg.Height != img.Bounds().Dy() {
		t.Fatalf("config %dx%d, image %v", cfg.Width, cfg.Height, img.Bounds())
	}
	if cfg.ColorModel != color.NRGBAModel {
		t.Fatalf("color model: %v", cfg.ColorModel)
	}
}

// TestWebpImageInterface checks that a parsed file works as an image.Image.
func TestWebpImageInterface(t *testing.T) {
	stream, err := os.ReadFile("testdata/alpha.webp")
	if err != nil {
		t.Skip("no fixture")
	}
	w, err := ParseWebpBytes(stream)
	if err != nil {
		t.Fatal(err)
	}
	var img image.Image = w
	if img.Bounds() != image.Rect(0, 0, 32, 32) {
		t.Fatalf("bounds: %v", img.Bounds())
	}
	if got := img.ColorModel(); got != color.NRGBAModel {
		t.Fatalf("color model: %v", got)
	}
	_ = img.At(3, 4)
	// the decoded image is cached, a second call must not decode again
	if _, err = w.Image(); err != nil {
		t.Fatal(err)
	}
}

// TestAnimationFrames decodes the animated fixture and compares every
// composited frame with the reference render.
func TestAnimationFrames(t *testing.T) {
	stream, err := os.ReadFile("testdata/anim.webp")
	if err != nil {
		t.Skip("no animated fixture")
	}
	w, err := ParseWebpBytes(stream)
	if err != nil {
		t.Fatal(err)
	}
	if !w.HasAnimation || len(w.ANMFs) != 3 {
		t.Fatalf("animation: flag=%v frames=%d", w.HasAnimation, len(w.ANMFs))
	}
	frames, durations, err := w.Frames(0)
	if err != nil {
		t.Fatal(err)
	}
	if len(frames) != 3 {
		t.Fatalf("got %d frames", len(frames))
	}
	for i, frame := range frames {
		golden, err := os.ReadFile(fmt.Sprintf("testdata/anim_%d.rgba", i))
		if err != nil {
			t.Skipf("no reference for frame %d", i)
		}
		compareNRGBA(t, fmt.Sprintf("frame %d", i), frame, golden)
		if durations[i] != 100 {
			t.Fatalf("frame %d duration %d", i, durations[i])
		}
	}
	// ToImage returns the first frame of an animated file
	img, err := w.ToImage()
	if err != nil {
		t.Fatal(err)
	}
	golden, _ := os.ReadFile("testdata/anim_0.rgba")
	compareNRGBA(t, "first frame", img, golden)
}

// TestConcurrentAccess hammers the cached image from several goroutines: the
// lazy decode is guarded by sync.Once, so run this under -race.
func TestConcurrentAccess(t *testing.T) {
	stream, err := os.ReadFile("testdata/alpha.webp")
	if err != nil {
		t.Skip("no fixture")
	}
	w, err := ParseWebpBytes(stream)
	if err != nil {
		t.Fatal(err)
	}
	var wg sync.WaitGroup
	for i := 0; i < 8; i++ {
		wg.Add(1)
		go func(i int) {
			defer wg.Done()
			for j := 0; j < 50; j++ {
				_ = w.At(j%32, i%32)
				_ = w.Bounds()
				_ = w.ColorModel()
				if _, err := w.Image(); err != nil {
					t.Error(err)
					return
				}
			}
		}(i)
	}
	wg.Wait()
}
